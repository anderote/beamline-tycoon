import assert from 'node:assert/strict';
import * as THREE from 'three';
import { StaticRoleBatches } from '../src/renderer3d/static-role-batches.js';
globalThis.THREE = THREE;
const parent = new THREE.Group();
parent.position.x = 100;
const geometry = new THREE.BoxGeometry();
const material = new THREE.MeshStandardMaterial();
const roots = [1, 2].map(id => {
  const root = new THREE.Group(); root.position.x = id * 3; root.userData.nodeId = id;
  const mesh = new THREE.Mesh(geometry, material);
  mesh.position.y = 2;
  mesh.userData = { role: 'metal', sharedGeometry: true };
  mesh.castShadow = true;
  root.add(mesh); parent.add(root); return root;
});
const batches = new StaticRoleBatches();
batches.rebuild(roots);
assert.equal(batches.meshes.length, 1);
const batch = batches.meshes[0];
assert.equal(batch.count, 2);
assert.deepEqual(batch.userData.componentIds, [1, 2]);
const matrix = new THREE.Matrix4(); batch.getMatrixAt(1, matrix);
assert.deepEqual(new THREE.Vector3().setFromMatrixPosition(matrix).toArray(), [6, 2, 0]);
assert.equal(batch.castShadow, true);
assert.ok(roots.every(root => root.children[0].visible === false));
parent.updateMatrixWorld(true);
const raycaster = new THREE.Raycaster(new THREE.Vector3(106, 2, 5), new THREE.Vector3(0, 0, -1));
assert.equal(raycaster.intersectObject(batch)[0].instanceId, 1, 'instance picking preserves source index');
roots[1].position.x = 9;
assert.equal(batches.syncTransforms(), 1);
batch.getMatrixAt(1, matrix);
assert.deepEqual(new THREE.Vector3().setFromMatrixPosition(matrix).toArray(), [9, 2, 0]);
assert.equal(batches.syncTransforms(), 0, 'steady wrappers do not upload matrices');
assert.equal(roots[1].children[0].userData.instancedRoleSource, true);
batches.setVisible(false); assert.equal(batch.visible, false);
batches.clear(); assert.ok(roots.every(root => root.children[0].visible));
roots[1].children[0].material = new THREE.MeshStandardMaterial({ transparent: true, opacity: 0.3 });
batches.rebuild(roots);
assert.equal(batches.meshes.length, 0, 'focused/dimmed parts remain independently rendered');
assert.ok(roots.every(root => root.children[0].visible));
console.log('Static component batching transforms, picking, focus and restore pass');
